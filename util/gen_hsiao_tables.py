# Generates the precomputed Hsiao matrices in hsiao_ecc_pkg.sv.
#
# The search is a port of hsiao_ecc_pkg::hsiao_matrix() and must stay bit-identical to it:
# the tables replace the SystemVerilog search for the listed sizes.

import argparse
import itertools
import pathlib
import re
import sys

MAX_DATA_WIDTH = 1024
MAX_PARITY_WIDTH = 20

# (data width, parity width); parity width None selects min_ecc(data width)
DEFAULT_SIZES = [
    (1, None), (4, None), (7, None), (9, None), (10, None), (13, None), (18, None), (20, None),
    (28, None), (32, None), (38, None), (41, None), (49, None), (64, None), (97, None),
    (126, None), (128, None), (137, None),
]

PKG = pathlib.Path(__file__).resolve().parent.parent / "rtl" / "hsiao_ecc" / "hsiao_ecc_pkg.sv"
BEGIN = "// BEGIN generated by util/gen_hsiao_tables.py ({}), do not edit"
END = "// END generated ({})"


def min_ecc(data_width):
    for i in range(MAX_PARITY_WIDTH):
        if 2**i >= data_width + i + 1:
            return i + 1
    raise ValueError(f"data width {data_width} too large for {MAX_PARITY_WIDTH} parity bits")


def hsiao_matrix(k, m):
    """Returns one k-bit integer per parity bit; bit j set if data bit j feeds that parity bit."""
    if k > MAX_DATA_WIDTH or m > MAX_PARITY_WIDTH:
        raise ValueError(f"size {k}/{m} exceeds package limits")
    cols = []
    fanins = [0] * m
    needed = k
    work_fanin = 0
    for step in range(3, m + 1, 2):
        # itertools.combinations yields the same lexicographic order as the SV enumeration
        combs = list(itertools.combinations(range(m), step))
        if len(combs) < needed:
            for comb in combs:
                cols.append(comb)
                for p in comb:
                    fanins[p] += 1
            needed -= len(combs)
            continue
        used = [False] * len(combs)
        while needed > 0:
            min_fanin = min(fanins)
            max_fanin = max(fanins)
            min_count = fanins.count(min_fanin)
            pick = None
            next_fanin = None
            for first_pass in (True, False):
                for i, comb in enumerate(combs):
                    if used[i]:
                        continue
                    cand_max = max(max_fanin, max(fanins[p] + 1 for p in comb))
                    hits = sum(fanins[p] == min_fanin for p in comb)
                    next_fanin = cand_max if next_fanin is None else min(next_fanin, cand_max)
                    if (not first_pass or hits == min_count) and cand_max <= work_fanin:
                        pick = i
                        break
                if pick is not None:
                    break
            if pick is None:
                work_fanin = next_fanin
                continue
            used[pick] = True
            cols.append(combs[pick])
            for p in combs[pick]:
                fanins[p] += 1
            needed -= 1
        break
    if len(cols) != k:
        raise ValueError(f"did not fill all parity bits for {k}/{m}")
    return [sum(1 << j for j, comb in enumerate(cols) if i in comb) for i in range(m)]


def render(sizes):
    decls, lookup = [], []
    for n, (k, m) in enumerate(sizes):
        rows = hsiao_matrix(k, m)
        name = f"HsiaoCodes{k}x{m}"
        vals = ",\n".join(f"    {k}'h{rows[i]:0{(k + 3) // 4}x}" for i in reversed(range(m)))
        decls.append(f"  localparam bit [{m-1}:0][{k-1}:0] {name} = {{\n{vals}\n  }};")
        cond = "if     " if n == 0 else "else if"
        lookup.append(
            f"      {cond} (k == {k:3d} && m == {m}) existing[i][{k-1:3d}:0] = {name}[i];")
    return {"tables": "\n".join(decls), "lookup": "\n".join(lookup)}


def update(text, regions):
    for name, body in regions.items():
        pattern = re.compile(
            r"(?P<indent>[ ]*)" + re.escape(BEGIN.format(name)) + r"\n.*?\n[ ]*"
            + re.escape(END.format(name)), re.S)
        match = pattern.search(text)
        if not match:
            raise ValueError(f"markers for '{name}' not found")
        indent = match.group("indent")
        repl = f"{indent}{BEGIN.format(name)}\n{body}\n{indent}{END.format(name)}"
        text = text[:match.start()] + repl + text[match.end():]
    return text


def parse_sizes(arg):
    sizes = []
    for item in arg.split(","):
        k, _, m = item.partition(":")
        sizes.append((int(k), int(m) if m else None))
    return sizes


def main():
    parser = argparse.ArgumentParser(
        description="Generate the precomputed Hsiao matrices in hsiao_ecc_pkg.sv")
    parser.add_argument("--sizes", type=parse_sizes,
                        help="comma-separated data[:parity] widths (default: built-in list)")
    parser.add_argument("--pkg", type=pathlib.Path, default=PKG)
    parser.add_argument("--check", action="store_true",
                        help="fail if the package is not up to date instead of writing it")
    args = parser.parse_args()

    sizes = [(k, m if m is not None else min_ecc(k)) for k, m in (args.sizes or DEFAULT_SIZES)]
    text = args.pkg.read_text()
    new = update(text, render(sizes))
    if args.check:
        if new != text:
            sys.exit(f"{args.pkg} is out of date, run {pathlib.Path(__file__).name}")
        return
    args.pkg.write_text(new)


if __name__ == "__main__":
    main()
